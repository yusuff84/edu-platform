_CELL = ('width:64px;height:76px;border-radius:14px;background:rgba(255,255,255,.1);border:2px solid rgba(255,255,255,.25);'
         'display:grid;place-items:center;font-family:JetBrains Mono,monospace;font-size:46px;font-weight:700;color:#fff')
_OFF = _CELL.replace('color:#fff', 'color:rgba(255,255,255,.35)')
_LBL = 'font-size:24px;font-weight:800;color:#fff;margin-bottom:12px'
_W = 'display:flex;gap:10px;justify-content:center;font-size:22px;font-weight:800;color:rgba(255,255,255,.7);margin-top:8px'
_SUM = ('margin-top:12px;display:inline-block;padding:4px 18px;border-radius:12px;background:#fec466;color:#1b1f4b;'
        'font-family:JetBrains Mono,monospace;font-size:38px;font-weight:800')


def _triad(title, sub, chars, weights, total, border):
    cells = ''.join(f'<div style="{_CELL if c != "-" else _OFF}">{c}</div>' for c in chars)
    ws = ''.join(f'<span style="width:64px;text-align:center">{w}</span>' for w in weights)
    return (f'<div style="padding:20px 22px;border-radius:22px;border:2px solid {border};background:rgba(255,255,255,.06);text-align:center">'
            f'<div style="{_LBL}">{title}<div style="font-size:19px;color:rgba(255,255,255,.7);font-weight:700">{sub}</div></div>'
            f'<div style="display:flex;gap:10px;justify-content:center">{cells}</div>'
            f'<div style="{_W}">{ws}</div><div style="{_SUM}">{total}</div></div>')


